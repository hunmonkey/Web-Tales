CREATE TABLE SHELFVIEW_READER_POSITION
(
    USER_ID             varchar  NOT NULL,
    BOOK_ID             varchar  NOT NULL,
    LOCATOR_JSON        varchar  NOT NULL,
    PROGRESSION         real     NOT NULL,
    CONTENT_FINGERPRINT varchar  NOT NULL,
    UPDATED_AT          datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (USER_ID, BOOK_ID),
    FOREIGN KEY (USER_ID) REFERENCES USER (ID) ON DELETE CASCADE,
    FOREIGN KEY (BOOK_ID) REFERENCES BOOK (ID) ON DELETE CASCADE
);

CREATE INDEX IDX_SHELFVIEW_READER_POSITION_BOOK
    ON SHELFVIEW_READER_POSITION (BOOK_ID);

CREATE TABLE SHELFVIEW_BOOKMARK
(
    ID           varchar  NOT NULL PRIMARY KEY,
    USER_ID      varchar  NOT NULL,
    BOOK_ID      varchar  NOT NULL,
    LOCATOR_JSON varchar  NOT NULL,
    LABEL        varchar,
    NOTE         varchar,
    CREATED_AT   datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT   datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (USER_ID) REFERENCES USER (ID) ON DELETE CASCADE,
    FOREIGN KEY (BOOK_ID) REFERENCES BOOK (ID) ON DELETE CASCADE
);

CREATE INDEX IDX_SHELFVIEW_BOOKMARK_USER_BOOK
    ON SHELFVIEW_BOOKMARK (USER_ID, BOOK_ID);

CREATE INDEX IDX_SHELFVIEW_BOOKMARK_BOOK
    ON SHELFVIEW_BOOKMARK (BOOK_ID);

CREATE TABLE SHELFVIEW_READER_PREFERENCE
(
    USER_ID       varchar  NOT NULL,
    SCOPE_TYPE    varchar  NOT NULL,
    SCOPE_ID      varchar  NOT NULL,
    FORMAT        varchar  NOT NULL,
    SETTINGS_JSON varchar  NOT NULL,
    UPDATED_AT    datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (USER_ID, SCOPE_TYPE, SCOPE_ID, FORMAT),
    FOREIGN KEY (USER_ID) REFERENCES USER (ID) ON DELETE CASCADE
);

CREATE INDEX IDX_SHELFVIEW_READER_PREFERENCE_USER_FORMAT
    ON SHELFVIEW_READER_PREFERENCE (USER_ID, FORMAT);
